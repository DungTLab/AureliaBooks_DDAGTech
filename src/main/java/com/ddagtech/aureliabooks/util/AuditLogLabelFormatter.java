    private AuditLogLabelFormatter() {
    }

    /**
     * Returns the Vietnamese display label for a raw audit action code.
     *
     * @param action raw audit action identifier
     * @return localized Vietnamese label, or trimmed raw token when unmapped
     */
    public String formatAction(String action) {
        if (action == null || action.isBlank()) {
            return UNKNOWN_LABEL;
        }
        String normalized = action.trim().toUpperCase(Locale.ROOT);
        ActionMetadata meta = ACTION_METADATA.get(normalized);
        return meta != null ? meta.label() : action.trim();
    }

    /**
     * Returns the Tailwind badge color classes associated with a raw audit action code.
     *
     * @param action raw audit action identifier
     * @return Tailwind background/text/border utility classes
     */
    public String badgeClasses(String action) {
        ActionMetadata meta = lookupAction(action);
        return meta != null ? meta.badgeClasses() : DEFAULT_ACTION_META.badgeClasses();
    }

    /**
     * Returns the Bootstrap Icon class name associated with a raw audit action code.
     *
     * @param action raw audit action identifier
     * @return Bootstrap Icon CSS class (e.g. {@code bi-lock})
     */
    public String badgeIcon(String action) {
        ActionMetadata meta = lookupAction(action);
        return meta != null ? meta.iconClass() : DEFAULT_ACTION_META.iconClass();
    }

    /**
     * Returns the Vietnamese display label for a database table name recorded in an audit log.
     *
     * @param targetTable raw SQL table name
     * @return localized Vietnamese entity label, or trimmed table name when unmapped
     */
    public String formatTargetTable(String targetTable) {
        if (targetTable == null || targetTable.isBlank()) {
            return UNKNOWN_LABEL;
        }
        String normalized = targetTable.trim().toLowerCase(Locale.ROOT);
        return TARGET_TABLE_LABELS.getOrDefault(normalized, targetTable.trim());
    }

    private static ActionMetadata lookupAction(String action) {
        if (action == null || action.isBlank()) {
            return null;
        }
        return ACTION_METADATA.get(action.trim().toUpperCase(Locale.ROOT));
    }

    private record ActionMetadata(String label, String badgeClasses, String iconClass) {
    }
